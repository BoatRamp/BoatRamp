//! Generate `docs/src/reference/cli-reference.md` — the exhaustive, always-current
//! command/flag reference — from boatramp's clap [`Command`](clap::Command) tree.
//!
//! A small custom walker over `Command::get_subcommands()` / `get_arguments()` (rather
//! than `clap-markdown` or `clap_mangen`): it is the only approach that lets us emit the
//! repo's own `| Argument | Env | Default | Values | Description |` table idiom and a
//! clean, per-page heading-slug scheme, and it needs no extra dependency. `clap_mangen`
//! emits roff (not Markdown) and `clap-markdown` emits a fixed bullet layout with no
//! Env/Default/Values columns — neither fits.
//!
//! This page is a SEPARATE file from the hand-authored narrative `reference/cli.md`
//! (approach (b) in PLAN-docs-structure Lever 2): the narrative page keeps all its prose,
//! examples, curated sub-action tables and — crucially — its `#boatramp-*` / `#blob-*`
//! intra-page anchors (linked from ~25 other docs) completely untouched. This generated
//! page is the drift-proof mechanical source of truth the CI gate protects.

use std::fmt::Write as _;

use clap::{Arg, ArgAction, Command};

/// Machine marker + human instruction at the very top of the generated file.
const BANNER: &str = "<!-- @generated by `cargo xtask gen-docs` from boatramp's clap command tree (crates/boatramp). DO NOT EDIT THIS FILE BY HAND. Edit the #[arg(...)] attributes / doc-comments in crates/boatramp/src/ and run `cargo xtask gen-docs`. -->";

/// The hand-fixed front matter: title + a visible "generated" notice pointing readers at
/// the narrative page and telling editors where the content really lives.
const HEADER: &str = "\
# CLI reference (generated)

> **This page is generated.** It is the exhaustive, always-current list of every `boatramp`
> command, subcommand, flag, environment variable and default — rendered from the clap command
> tree by `cargo xtask gen-docs` and kept honest by a CI drift gate. **Do not edit it by hand:**
> change the `#[arg(...)]` attributes or doc-comments in `crates/boatramp/src/` and run
> `cargo xtask gen-docs`.
>
> For the narrative guide — with worked examples, cross-links and curated grouping — see
> [the CLI guide](./cli.md). This reference reflects the default (batteries-included) build; a
> command's one-line summary notes when it needs a specific `--features` build.
";

/// Render the full `cli-reference.md` content.
pub fn render() -> String {
    let cmd = boatramp::cli_command();

    let mut out = String::new();
    let _ = writeln!(out, "{BANNER}");
    out.push('\n');
    out.push_str(HEADER);
    out.push('\n');

    render_root(&mut out, &cmd);

    for sub in cmd.get_subcommands() {
        if sub.is_hide_set() {
            continue;
        }
        render_command(&mut out, sub, &format!("boatramp {}", sub.get_name()), 2);
    }

    // Exactly one trailing newline (stable output for byte-level `--check`).
    let mut out = out.trim_end().to_string();
    out.push('\n');
    out
}

/// The root `boatramp` section: its about + the global options accepted on every subcommand.
fn render_root(out: &mut String, cmd: &Command) {
    let _ = writeln!(out, "## `boatramp`\n");
    write_about(out, cmd);
    let _ = writeln!(out, "**Usage:** `{}`\n", usage("boatramp", cmd));
    let _ = writeln!(
        out,
        "These global options are accepted on **every** subcommand (listed once here, omitted from the per-command tables below):\n"
    );
    render_args_table(out, cmd);
}

/// Render one command (and recurse into its subcommands at the next heading level).
fn render_command(out: &mut String, cmd: &Command, path: &str, level: usize) {
    let hashes = "#".repeat(level.min(6));
    let _ = writeln!(out, "{hashes} `{path}`\n");
    write_about(out, cmd);
    let _ = writeln!(out, "**Usage:** `{}`\n", usage(path, cmd));
    render_args_table(out, cmd);

    for sub in cmd.get_subcommands() {
        if sub.is_hide_set() {
            continue;
        }
        render_command(out, sub, &format!("{path} {}", sub.get_name()), level + 1);
    }
}

/// Write the command's short `about` (from its doc-comment) as a paragraph, if any.
fn write_about(out: &mut String, cmd: &Command) {
    if let Some(about) = cmd.get_about() {
        let text = about.to_string();
        let text = text.trim();
        if !text.is_empty() {
            // Collapse the doc-comment's internal line wraps into one paragraph.
            let flowed = text
                .split('\n')
                .map(str::trim)
                .collect::<Vec<_>>()
                .join(" ");
            let _ = writeln!(out, "{flowed}\n");
        }
    }
}

/// A one-line synthetic usage string: `path [OPTIONS] <POSITIONALS> <COMMAND>`.
fn usage(path: &str, cmd: &Command) -> String {
    let mut u = String::from(path);
    if documented_args(cmd).any(|a| !a.is_positional()) {
        u.push_str(" [OPTIONS]");
    }
    for a in documented_args(cmd).filter(|a| a.is_positional()) {
        let vn = value_name(a);
        if a.is_required_set() {
            let _ = write!(u, " <{vn}>");
        } else {
            let _ = write!(u, " [{vn}]");
        }
    }
    if cmd.has_subcommands() {
        u.push_str(" <COMMAND>");
    }
    u
}

/// The arguments worth documenting: visible, and not clap's auto `--help`/`--version`.
fn documented_args(cmd: &Command) -> impl Iterator<Item = &Arg> {
    cmd.get_arguments()
        .filter(|a| !a.is_hide_set())
        .filter(|a| !matches!(a.get_id().as_str(), "help" | "version"))
}

/// Emit the `| Argument | Env | Default | Values | Description |` table (positionals first),
/// or nothing when the command has no documentable args.
fn render_args_table(out: &mut String, cmd: &Command) {
    let args: Vec<&Arg> = documented_args(cmd).collect();
    if args.is_empty() {
        return;
    }
    let _ = writeln!(out, "| Argument | Env | Default | Values | Description |");
    let _ = writeln!(out, "| --- | --- | --- | --- | --- |");
    for a in args.iter().filter(|a| a.is_positional()) {
        write_arg_row(out, a);
    }
    for a in args.iter().filter(|a| !a.is_positional()) {
        write_arg_row(out, a);
    }
    out.push('\n');
}

fn write_arg_row(out: &mut String, a: &Arg) {
    let name = format!("`{}`", cell(&invocation(a)));

    let env = a
        .get_env()
        .map(|e| format!("`{}`", cell(&e.to_string_lossy())))
        .unwrap_or_else(|| "—".to_string());

    let defaults: Vec<String> = a
        .get_default_values()
        .iter()
        .map(|d| d.to_string_lossy().into_owned())
        .collect();
    let default = if defaults.is_empty() {
        "—".to_string()
    } else {
        format!("`{}`", cell(&defaults.join(", ")))
    };

    // Only value-taking args have a meaningful value set; a boolean/count flag's implicit
    // true/false possible-values would just be noise in the table.
    let pvs: Vec<String> = if takes_value(a) {
        a.get_possible_values()
            .iter()
            .map(|p| p.get_name().to_string())
            .collect()
    } else {
        Vec::new()
    };
    let values = if pvs.is_empty() {
        "—".to_string()
    } else {
        cell(&pvs.join(" | "))
    };

    let help = a
        .get_help()
        .or_else(|| a.get_long_help())
        .map(|h| cell(&h.to_string()))
        .unwrap_or_else(|| "—".to_string());

    let _ = writeln!(out, "| {name} | {env} | {default} | {values} | {help} |");
}

/// How the argument is written on the command line: `<NAME>`/`[NAME]` for a positional, or
/// `-s, --long <VALUE>` for an option (no `<VALUE>` for a boolean/count flag).
fn invocation(a: &Arg) -> String {
    if a.is_positional() {
        let vn = value_name(a);
        return if a.is_required_set() {
            format!("<{vn}>")
        } else {
            format!("[{vn}]")
        };
    }
    let mut parts = Vec::new();
    if let Some(s) = a.get_short() {
        parts.push(format!("-{s}"));
    }
    if let Some(l) = a.get_long() {
        parts.push(format!("--{l}"));
    }
    let mut inv = parts.join(", ");
    if takes_value(a) {
        let _ = write!(inv, " <{}>", value_name(a));
    }
    inv
}

/// The value placeholder for an arg: its declared value name, else the id upper-cased.
fn value_name(a: &Arg) -> String {
    if let Some(first) = a.get_value_names().and_then(|names| names.first()) {
        return first.to_string();
    }
    a.get_id().as_str().to_uppercase()
}

/// Whether the arg consumes a value (vs. a boolean/count/help/version flag).
fn takes_value(a: &Arg) -> bool {
    matches!(a.get_action(), ArgAction::Set | ArgAction::Append)
}

/// Sanitise a string for a single Markdown table cell: flatten newlines and escape pipes.
fn cell(s: &str) -> String {
    s.replace(['\r', '\n'], " ")
        .replace('|', "\\|")
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}
